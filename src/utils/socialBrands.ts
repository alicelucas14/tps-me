/** Find a brand from a URL's domain (e.g. facebook.com → Facebook). */
export function detectBrandFromUrl(url: string): SocialBrand | undefined {
  let host = "";
  try {
    host = new URL((url || "").trim()).hostname.toLowerCase().replace(/^www\./, "");
  } catch {
    return undefined;
  }
  if (!host) return undefined;
  return SOCIAL_BRANDS.find((b) => b.domains.some((d) => host === d || host.endsWith(`.${d}`)));
}

/** Find which brand an icon path belongs to. */
export function findBrandByPath(path: string): SocialBrand | undefined {
  if (!path) return undefined;
  return SOCIAL_BRANDS.find((b) => b.path === path || (b.altPaths || []).includes(path));
}

/** Names that are safe to overwrite when the brand changes (placeholders or other brand names). */
export function isGenericSocialName(name: string): boolean {
  const n = (name || "").trim().toLowerCase();
  if (!n || n === "community" || n === "social" || n === "new profile" || n === "twitter" || n === "x") return true;
  return SOCIAL_BRANDS.some((b) => b.name.toLowerCase() === n);
}

/** True if the URL is empty or just a bare brand homepage (no handle yet). */
export function isPlaceholderSocialUrl(url: string): boolean {
  const u = (url || "").trim().toLowerCase().replace(/\/+$/, "");
  if (!u || u === "https:" || u === "https://") return true;
  return SOCIAL_BRANDS.some((b) => {
    const base = b.baseUrl.toLowerCase().replace(/[/@]+$/, "");
    return base.length > 8 && (u === base || u === base.replace("://www.", "://"));
  }) || ["https://facebook.com", "https://youtube.com", "https://x.com", "https://instagram.com", "https://t.me", "https://wa.me", "https://discord.com"].includes(u);
}
